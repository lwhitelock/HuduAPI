    .SYNOPSIS
    Normalize a currency code, falling back to the session culture and then USD.

    .DESCRIPTION
    Accepts current ISO 4217 codes and retained legacy codes for existing layouts.
    Missing or invalid codes use Get-Culture (the executing session's formatting culture),
    not the Hudu server's locale. Invariant or unavailable regional currencies use USD.
    #>
