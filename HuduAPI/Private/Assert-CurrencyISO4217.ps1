    if ($CurrencyCode -match '^[A-Z]{3}$' -and $CurrencyCode -in $ValidCurrencyCodes) {
        return $CurrencyCode
    }

    try {
        $Region = [System.Globalization.RegionInfo]::new((Get-Culture -ErrorAction Stop).Name)
        $CurrencyCode = $Region.ISOCurrencySymbol
